import 'dotenv/config';
import {createServer} from 'node:http';
import {readFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {Pool} from 'pg';
import {adminConfigSchema} from '../src/lib/admin-security';
import {AdminMaintenance} from '../src/lib/admin-maintenance';
import {createAdminHandler} from '../src/lib/admin-http';
const file=process.env.CREDENTIALS_DIRECTORY?join(process.env.CREDENTIALS_DIRECTORY,'admin-config'):process.env.ADMIN_CONFIG_FILE;
if(!file)throw new Error('缺少私有管理员配置文件');
const config=adminConfigSchema.parse(JSON.parse(readFileSync(file,'utf8'))),origin=new URL(process.env.APP_URL??'http://127.0.0.1:3101').origin;
const pool=new Pool({connectionString:process.env.DATABASE_URL,max:4,connectionTimeoutMillis:5000,query_timeout:10000});
const service=new AdminMaintenance(pool,resolve(process.cwd()));
const workerLock=await pool.connect();
if(!(await workerLock.query("SELECT pg_try_advisory_lock(hashtext('life-in-order-admin-worker')) AS locked")).rows[0].locked)throw new Error('已有管理服务正在运行');
await service.recover();
const handler=createAdminHandler(service,config,origin);
const server=createServer({maxHeaderSize:16384},(req,res)=>{void handler(req,res);});
server.requestTimeout=30000;server.headersTimeout=15000;
server.listen(Number(process.env.ADMIN_PORT??3101),'127.0.0.1',()=>console.log('生活有序管理服务已启动，仅监听本机回环地址。'));
const timer=setInterval(()=>{void service.runNext().catch(()=>console.error('维护任务读取失败，请检查数据库。'));},2000);timer.unref();
process.on('SIGTERM',()=>{clearInterval(timer);server.close(()=>{workerLock.release();void pool.end().then(()=>process.exit(0));});});
